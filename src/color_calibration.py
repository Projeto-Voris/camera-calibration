def simulate_synthetic_chart_image(
    noise_sigma: float = 0.0,
    distortion_matrix: Optional[np.ndarray] = None
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Gera uma imagem sintética renderizada do gráfico de machbeth_generator.py
    com dimensões 600x400 para testes automatizados.

    :return: (imagem_sintetica_bgr, cantos_verdadeiros)
    """
    img_w, img_h = 600, 400
    canvas = np.ones((img_h, img_w, 3), dtype=np.uint8) * 40  # Fundo escuro

    rows, cols = 4, 6
    cell_w = img_w / cols
    cell_h = img_h / rows

    if distortion_matrix is None:
        # Simula pequena perda espectral do sensor (ex: atenuação no azul, cross-talk)
        distortion_matrix = np.array([
            [0.88, 0.08, 0.04],
            [0.05, 0.92, 0.03],
            [0.02, 0.10, 0.85]
        ], dtype=np.float64)

    t_matrix = get_standard_srgb_matrix(normalized=False)  # (3, 24)

    for idx in range(24):
        r = idx // cols
        c = idx % cols

        x0 = int(c * cell_w + 6)
        x1 = int((c + 1) * cell_w - 6)
        y0 = int(r * cell_h + 6)
        y1 = int((r + 1) * cell_h - 6)

        ideal_rgb = t_matrix[:, idx]
        distorted_rgb = distortion_matrix @ ideal_rgb

        if noise_sigma > 0:
            distorted_rgb += np.random.normal(0, noise_sigma, 3)

        distorted_rgb = np.clip(distorted_rgb, 0, 255).astype(np.uint8)
        bgr = (int(distorted_rgb[2]), int(distorted_rgb[1]), int(distorted_rgb[0]))

        cv2.rectangle(canvas, (x0, y0), (x1, y1), bgr, -1)
        cv2.rectangle(canvas, (x0, y0), (x1, y1), (20, 20, 20), 1)

    corners = np.array([
        [0, 0],
        [img_w - 1, 0],
        [img_w - 1, img_h - 1],
        [0, img_h - 1]
    ], dtype=np.float32)

    return canvas, corners


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Calibração de Cor Macbeth para Câmeras FLIR")
    parser.add_argument("--image", type=str, help="Caminho para a imagem capturada do gráfico Macbeth")
    parser.add_argument("--target", type=str, default="standard_srgb", choices=["standard_srgb", "cmyk_nominal"],
                        help="Espaço de cor alvo de referência")
    parser.add_argument("--method", type=str, default="white_point_preserving",
                        choices=["flir_least_squares", "white_point_preserving", "weighted_least_squares"],
                        help="Método de cálculo da CCM")
    parser.add_argument("--interactive", action="store_true", help="Selecionar 4 cantos interativamente via GUI")
    parser.add_argument("--output_yaml", type=str, default="camera_parameters/flir_color_correction.yaml",
                        help="Arquivo YAML de saída para os parâmetros FLIR")
    parser.add_argument("--output_plot", type=str, default="output/color_calibration_results.png",
                        help="Imagem PNG de saída com o relatório gráfico")
    parser.add_argument("--simulate", action="store_true", help="Executar teste de simulação com dados sintéticos")

    args = parser.parse_args()

    calib = ColorCalibration(target_type=args.target)

    if args.simulate or args.image is None:
        print("Executando calibração em modo de simulação...")
        img, corners = simulate_synthetic_chart_image()
        calib.extract_patches_from_corners(img, corners)
    else:
        if not os.path.exists(args.image):
            raise FileNotFoundError(f"Imagem não encontrada: {args.image}")
        img = cv2.imread(args.image)
        if args.interactive:
            calib.extract_patches_interactive(img)
        else:
            # Se não interativo e sem cantos, usa as bordas da imagem como estimativa
            h, w = img.shape[:2]
            corners = np.array([[0, 0], [w - 1, 0], [w - 1, h - 1], [0, h - 1]], dtype=np.float32)
            calib.extract_patches_from_corners(img, corners)

    ccm = calib.solve_ccm(method=args.method)
    metrics = calib.evaluate_metrics()

    print("\n" + "=" * 60)
    print("RESULTADOS DA CALIBRAÇÃO DE COR FLIR")
    print("=" * 60)
    print(f"Matriz CCM calculada:\n{ccm}")
    print(f"RMSE RGB: {metrics['rmse_before']:.2f} -> {metrics['rmse_after']:.2f} ({metrics['improvement_pct']:.1f}% melhoria)")
    print(f"Delta E CIE76 Médio: {metrics['delta_e_mean_before']:.2f} -> {metrics['delta_e_mean_after']:.2f}")
    print("=" * 60)

    calib.export_flir_yaml(args.output_yaml)
    calib.plot_calibration_results(args.output_plot)

    # Exibir trecho de código PySpin
    pyspin_code = calib.generate_pyspin_snippet()
    pyspin_path = os.path.join(os.path.dirname(args.output_yaml), "apply_flir_ccm.py")
    with open(pyspin_path, "w", encoding="utf-8") as f:
        f.write(pyspin_code)
    print(f"Script de configuração PySpin salvo em: {pyspin_path}")
