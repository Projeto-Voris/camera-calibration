def rgb_to_xyz(rgb: np.ndarray) -> np.ndarray:
    """
    Converte RGB linear sRGB [0, 1] em CIE XYZ (iluminante D65).
    Forma de entrada: (3, N) ou (N, 3)
    """
    transposed = False
    if rgb.shape[0] != 3 and rgb.shape[1] == 3:
        rgb = rgb.T
        transposed = True

    # Matriz sRGB D65 para XYZ
    M = np.array([
        [0.4124564, 0.3575761, 0.1804375],
        [0.2126729, 0.7151522, 0.0721750],
        [0.0193339, 0.1191920, 0.9503041]
    ], dtype=np.float64)

    xyz = M @ rgb
    return xyz.T if transposed else xyz


def xyz_to_lab(xyz: np.ndarray) -> np.ndarray:
    """
    Converte CIE XYZ em CIELAB (D65 ponto branco de referência: 0.95047, 1.0, 1.08883).
    Forma: (3, N)
    """
    # Referência D65
    Xn, Yn, Zn = 0.95047, 1.00000, 1.08883

    x = xyz[0] / Xn
    y = xyz[1] / Yn
    z = xyz[2] / Zn

    delta = 6.0 / 29.0

    def f(t):
        return np.where(t > delta**3, np.cbrt(t), t / (3 * delta**2) + 4.0 / 29.0)

    fx = f(x)
    fy = f(y)
    fz = f(z)

    L = 116.0 * fy - 16.0
    a = 500.0 * (fx - fy)
    b = 200.0 * (fy - fz)

    return np.vstack([L, a, b])


def calculate_delta_e76(rgb1: np.ndarray, rgb2: np.ndarray, max_val: float = 255.0) -> np.ndarray:
    """
    Calcula Delta E CIE 1976 entre dois conjuntos de cores RGB (3, N).
    """
    rgb1_norm = np.clip(rgb1 / max_val, 0.0, 1.0)
    rgb2_norm = np.clip(rgb2 / max_val, 0.0, 1.0)

    # Linearização simples para sRGB (gamma)
    def srgb_to_linear(c):
        return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)

    lab1 = xyz_to_lab(rgb_to_xyz(srgb_to_linear(rgb1_norm)))
    lab2 = xyz_to_lab(rgb_to_xyz(srgb_to_linear(rgb2_norm)))

    delta_e = np.sqrt(np.sum((lab1 - lab2) ** 2, axis=0))
    return delta_e


class ColorCalibration:
    """
    Classe para calibrar cores de câmeras FLIR a partir do gráfico Macbeth ColorChecker.
    Calcula a Matriz de Correção de Cor (CCM) 3x3:
        [R_target]   [Gain00 Gain01 Gain02] [R_source]
        [G_target] = [Gain10 Gain11 Gain12] [G_source]
        [B_target]   [Gain20 Gain21 Gain22] [B_source]
    """

    GAIN_NAMES = [
        ("Gain00", 0, 0), ("Gain01", 0, 1), ("Gain02", 0, 2),
        ("Gain10", 1, 0), ("Gain11", 1, 1), ("Gain12", 1, 2),
        ("Gain20", 2, 0), ("Gain21", 2, 1), ("Gain22", 2, 2)
    ]

    def __init__(self, target_type: str = "standard_srgb", normalized: bool = False):
        """
        :param target_type: 'standard_srgb' (BabelColor sRGB) ou 'cmyk_nominal' (nominal do machbeth_generator.py)
        :param normalized: Se True, RGB em [0.0, 1.0]; se False, em [0.0, 255.0].
        """
        self.target_type = target_type
        self.normalized = normalized
        self.max_val = 1.0 if normalized else 255.0

        # Carregar matriz de cores alvo (3 x 24)
        if target_type == "standard_srgb":
            self.T = get_standard_srgb_matrix(normalized=normalized)
        elif target_type == "cmyk_nominal":
            self.T = get_cmyk_nominal_rgb_matrix(normalized=normalized)
        else:
            raise ValueError(f"target_type desconhecido: {target_type}. Use 'standard_srgb' ou 'cmyk_nominal'.")

        self.S: Optional[np.ndarray] = None          # Matriz fonte capturada (3 x 24)
        self.CCM: Optional[np.ndarray] = None        # Matriz CCM calculada (3 x 3)
        self.rectified_image: Optional[np.ndarray] = None
        self.rectified_rois: List[Tuple[int, int, int, int]] = []
        self.sample_points: List[Tuple[float, float]] = []

    def set_target_matrix(self, T: np.ndarray):
        """Define matriz de cores alvo personalizada (3, 24)."""
        if T.shape != (3, 24):
            raise ValueError(f"A matriz alvo deve ter formato (3, 24), recebido {T.shape}")
        self.T = T.astype(np.float64)

    def set_source_matrix(self, S: np.ndarray):
        """Define matriz de cores fonte da câmera (3, 24)."""
        if S.shape != (3, 24):
            raise ValueError(f"A matriz fonte deve ter formato (3, 24), recebido {S.shape}")
        self.S = S.astype(np.float64)

    def extract_patches_from_rois(
        self,
        image: np.ndarray,
        rois: List[Optional[Tuple[int, int, int, int]]],
    ) -> np.ndarray:
        """
        Extrai as cores médias dos 24 patches a partir de bounding boxes (ROIs) definidas
        pelo usuário na imagem original (sem retificação em perspectiva).

        :param image: Imagem colorida BGR (OpenCV).
        :param rois: Lista de 24 entradas; cada entrada é (x, y, w, h) em pixels
                     na imagem original, ou None se o patch ainda não foi definido.
        :return: Matriz de cores fonte S (3, 24). Patches sem ROI recebem [0, 0, 0].
        """
        if len(rois) != 24:
            raise ValueError(f"São necessárias exatamente 24 ROIs, recebido {len(rois)}")

        is_bgr = len(image.shape) == 3 and image.shape[2] == 3
        h_img, w_img = image.shape[:2]

        patch_colors = []
        self.rectified_rois = []

        for idx, roi in enumerate(rois):
            if roi is None:
                patch_colors.append(np.array([0.0, 0.0, 0.0]))
                self.rectified_rois.append((0, 0, 0, 0))
                continue

            x, y, w, h = int(roi[0]), int(roi[1]), int(roi[2]), int(roi[3])
            # Garantir que a ROI está dentro da imagem
            x = max(0, min(x, w_img - 1))
            y = max(0, min(y, h_img - 1))
            w = max(1, min(w, w_img - x))
            h = max(1, min(h, h_img - y))

            self.rectified_rois.append((x, y, w, h))
            roi_crop = image[y:y + h, x:x + w]

            if roi_crop.size == 0:
                mean_color = np.array([0.0, 0.0, 0.0])
            else:
                mean_bgr = np.mean(roi_crop, axis=(0, 1))
                if is_bgr:
                    mean_color = mean_bgr[::-1].copy()  # BGR → RGB
                else:
                    mean_color = mean_bgr.copy()

            if self.normalized:
                mean_color = mean_color / 255.0

            patch_colors.append(mean_color)

        self.S = np.array(patch_colors, dtype=np.float64).T  # (3, 24)
        return self.S

    def extract_patches_from_corners(
        self,
        image: np.ndarray,
        corners: np.ndarray,
        target_size: Tuple[int, int] = (600, 400),
        roi_ratio: float = 0.5
    ) -> np.ndarray:
        """
        Retifica a imagem do gráfico Macbeth a partir de 4 cantos e extrai os 24 patches.

        :param image: Imagem colorida BGR ou RGB (OpenCV lê BGR).
        :param corners: 4 pontos ordenados [Top-Left, Top-Right, Bottom-Right, Bottom-Left].
        :param target_size: (largura, altura) da imagem retificada (default: 600x400).
        :param roi_ratio: Fração central de cada patch usada para calcular a média (default: 0.5 = 50%).
        :return: Matriz de cores fonte S (3, 24) em formato RGB.
        """
        corners = np.array(corners, dtype=np.float32)
        if corners.shape != (4, 2):
            raise ValueError(f"Os cantos devem ser 4 pontos (4, 2), recebido {corners.shape}")

        tw, th = target_size
        dst_pts = np.array([
            [0, 0],
            [tw - 1, 0],
            [tw - 1, th - 1],
            [0, th - 1]
        ], dtype=np.float32)

        M = cv2.getPerspectiveTransform(corners, dst_pts)
        rectified = cv2.warpPerspective(image, M, (tw, th))
        self.rectified_image = rectified.copy()

        # Grade de 4 linhas x 6 colunas
        rows, cols = 4, 6
        cell_w = tw / cols
        cell_h = th / rows

        patch_colors = []
        self.rectified_rois = []
        self.sample_points = []

        for idx in range(24):
            r = idx // cols
            c = idx % cols

            cx = (c + 0.5) * cell_w
            cy = (r + 0.5) * cell_h
            self.sample_points.append((cx, cy))

            rw = cell_w * roi_ratio
            rh = cell_h * roi_ratio

            x0 = int(round(cx - rw / 2.0))
            x1 = int(round(cx + rw / 2.0))
            y0 = int(round(cy - rh / 2.0))
            y1 = int(round(cy + rh / 2.0))

            x0 = max(0, min(tw - 1, x0))
            x1 = max(0, min(tw, x1))
            y0 = max(0, min(th - 1, y0))
            y1 = max(0, min(th, y1))

            self.rectified_rois.append((x0, y0, x1 - x0, y1 - y0))

            roi = rectified[y0:y1, x0:x1]
            if roi.size == 0:
                mean_color = np.array([0.0, 0.0, 0.0])
            else:
                # Se imagem tiver 3 canais (BGR), converter para RGB
                if len(image.shape) == 3 and image.shape[2] == 3:
                    mean_color = np.mean(roi, axis=(0, 1))[::-1]  # BGR para RGB
                else:
                    mean_color = np.mean(roi, axis=(0, 1))

            if self.normalized:
                mean_color = mean_color / 255.0

            patch_colors.append(mean_color)

        self.S = np.array(patch_colors, dtype=np.float64).T  # (3, 24)
        return self.S

    def extract_patches_interactive(
        self,
        image: np.ndarray,
        target_size: Tuple[int, int] = (600, 400),
        roi_ratio: float = 0.5,
        window_title: str = "Selecione 4 cantos: TL -> TR -> BR -> BL (ESC para sair)"
    ) -> np.ndarray:
        """
        Permite ao usuário clicar interativamente nos 4 cantos do gráfico Macbeth.
        Ordem de clique:
          1. Canto Superior-Esquerdo (Patch 1 - Dark Skin)
          2. Canto Superior-Direito (Patch 6 - Bluish Green)
          3. Canto Inferior-Direito (Patch 24 - Black 2)
          4. Canto Inferior-Esquerdo (Patch 19 - White 0.05)
        """
        pts: List[List[int]] = []
        disp = image.copy()

        def on_mouse(event, x, y, flags, param):
            if event == cv2.EVENT_LBUTTONDOWN and len(pts) < 4:
                pts.append([x, y])
                cv2.circle(disp, (x, y), 5, (0, 0, 255), -1)
                cv2.putText(disp, f"{len(pts)}", (x + 8, y - 8),
                            cv2.FONT_HERSHEY_SIMPLEX, 0.6, (0, 255, 0), 2)
                cv2.imshow(window_title, disp)

        cv2.namedWindow(window_title, cv2.WINDOW_NORMAL)
        cv2.setMouseCallback(window_title, on_mouse)
        cv2.imshow(window_title, disp)

        print(f"Instruções: Clique nos 4 cantos do gráfico Macbeth na janela aberta:")
        print("  1. Canto Superior-Esquerdo (Perto do Patch 1 - Dark Skin)")
        print("  2. Canto Superior-Direito (Perto do Patch 6 - Bluish Green)")
        print("  3. Canto Inferior-Direito (Perto do Patch 24 - Black)")
        print("  4. Canto Inferior-Esquerdo (Perto do Patch 19 - White)")

        while len(pts) < 4:
            key = cv2.waitKey(20) & 0xFF
            if key == 27:  # ESC
                cv2.destroyWindow(window_title)
                raise RuntimeError("Seleção de cantos cancelada pelo usuário.")

        cv2.destroyWindow(window_title)
        return self.extract_patches_from_corners(image, np.array(pts), target_size=target_size, roi_ratio=roi_ratio)

    def solve_ccm(
        self,
        method: str = "flir_least_squares",
        weights: Optional[np.ndarray] = None
    ) -> np.ndarray:
        """
        Calcula a Matriz de Correção de Cor (CCM) 3x3 tal que:
            T = CCM * S

        :param method:
            - 'flir_least_squares': Solução exata de mínimos quadrados descrita na nota de aplicação da FLIR:
                                   CCM = T * S^T * (S * S^T)^(-1)
            - 'white_point_preserving': Mínimos quadrados com restrição de preservação do ponto branco:
                                        cada linha do CCM soma exatamente 1.0 (soma_j CCM[i, j] = 1.0).
            - 'weighted_least_squares': Mínimos quadrados ponderados por pesos por patch.
        :param weights: Vetor de pesos (24,) opcional para dar maior importância a certos patches.
        :return: Matriz CCM (3, 3).
        """
        if self.S is None:
            raise ValueError("Matriz fonte S não definida. Chame extract_patches_* ou set_source_matrix primeiro.")

        T = self.T  # (3, 24)
        S = self.S  # (3, 24)

        if method == "flir_least_squares":
            # Fórmula direta da aplicação FLIR:
            # CCM = T * S^T * inv(S * S^T)
            S_ST = S @ S.T  # (3, 3)
            T_ST = T @ S.T  # (3, 3)
            try:
                self.CCM = T_ST @ np.linalg.inv(S_ST)
            except np.linalg.LinAlgError:
                # Fallback para pseudo-inversa se singular
                self.CCM = T @ np.linalg.pinv(S)

        elif method == "white_point_preserving":
            # Minimiza ||S^T * x_i - T_i^T||^2 sujeito a C * x_i = 1, onde C = [1, 1, 1]
            # Solução analítica fechada via multiplicador de Lagrange:
            # x_i = (A^T A)^(-1) A^T b + (A^T A)^(-1) C^T [C (A^T A)^(-1) C^T]^(-1) (1 - C (A^T A)^(-1) A^T b)
            A = S.T  # (24, 3)
            ATA = A.T @ A  # (3, 3)
            ATA_inv = np.linalg.pinv(ATA)
            C = np.array([[1.0, 1.0, 1.0]])  # (1, 3)

            denom = C @ ATA_inv @ C.T  # (1, 1)
            scale = ATA_inv @ C.T / denom

            ccm_rows = []
            for i in range(3):
                b = T[i, :].reshape(-1, 1)  # (24, 1)
                x_unconstrained = ATA_inv @ A.T @ b  # (3, 1)
                constraint_diff = 1.0 - (C @ x_unconstrained)[0, 0]
                x_constrained = x_unconstrained + scale * constraint_diff
                ccm_rows.append(x_constrained.flatten())

            self.CCM = np.array(ccm_rows, dtype=np.float64)

        elif method == "weighted_least_squares":
            if weights is None:
                # Peso padrão: patches neutros (19 a 24) com peso maior (2.0), outros peso 1.0
                weights = np.ones(24, dtype=np.float64)
                weights[18:24] = 2.0
            W = np.diag(weights)
            S_W = S @ W
            self.CCM = (T @ W @ S.T) @ np.linalg.pinv(S_W @ S.T)

        else:
            raise ValueError(f"Método desconhecido: {method}")

        return self.CCM

    def apply_ccm(self, rgb: np.ndarray) -> np.ndarray:
        """
        Aplica a CCM em dados RGB (3, N) ou imagem HxW x 3.
        """
        if self.CCM is None:
            raise ValueError("CCM não calculada. Chame solve_ccm() primeiro.")

        if rgb.ndim == 2 and rgb.shape[0] == 3:
            corrected = self.CCM @ rgb
            return np.clip(corrected, 0.0, self.max_val)
        elif rgb.ndim == 3 and rgb.shape[2] == 3:
            h, w, _ = rgb.shape
            reshaped = rgb.reshape(-1, 3).T
            corrected = self.CCM @ reshaped
            corrected = np.clip(corrected, 0.0, self.max_val).T.reshape(h, w, 3)
            return corrected
        else:
            raise ValueError(f"Formato RGB não suportado: {rgb.shape}")

    def get_flir_gains(self) -> Dict[str, float]:
        """
        Retorna o dicionário com os valores Gain00 a Gain22 correspondentes aos nós da câmera FLIR.
        """
        if self.CCM is None:
            raise ValueError("CCM não calculada.")

        gains = {}
        for name, r, c in self.GAIN_NAMES:
            gains[name] = float(self.CCM[r, c])
        return gains

    def evaluate_metrics(self) -> Dict[str, Any]:
        """
        Avalia as métricas de erro antes e depois da calibração:
          - RMSE RGB
          - Erro Máximo RGB
          - Delta E CIE76 médio e máximo
        """
        if self.S is None or self.CCM is None:
            raise ValueError("S e CCM precisam estar definidos.")

        S_corrected = self.apply_ccm(self.S)

        # Erro RGB
        err_before = np.linalg.norm(self.T - self.S, axis=0)
        err_after = np.linalg.norm(self.T - S_corrected, axis=0)

        rmse_before = float(np.sqrt(np.mean(err_before ** 2)))
        rmse_after = float(np.sqrt(np.mean(err_after ** 2)))

        # Delta E CIELAB
        de_before = calculate_delta_e76(self.T, self.S, max_val=self.max_val)
        de_after = calculate_delta_e76(self.T, S_corrected, max_val=self.max_val)

        mean_de_before = float(np.mean(de_before))
        mean_de_after = float(np.mean(de_after))
        max_de_before = float(np.max(de_before))
        max_de_after = float(np.max(de_after))

        improvement_pct = float((1.0 - (rmse_after / max(1e-6, rmse_before))) * 100.0)

        return {
            "rmse_before": rmse_before,
            "rmse_after": rmse_after,
            "max_err_before": float(np.max(err_before)),
            "max_err_after": float(np.max(err_after)),
            "delta_e_mean_before": mean_de_before,
            "delta_e_mean_after": mean_de_after,
            "delta_e_max_before": max_de_before,
            "delta_e_max_after": max_de_after,
            "improvement_pct": improvement_pct,
            "per_patch_err_before": err_before.tolist(),
            "per_patch_err_after": err_after.tolist(),
            "per_patch_de_before": de_before.tolist(),
            "per_patch_de_after": de_after.tolist(),
        }

    def export_flir_yaml(self, filepath: str, camera_name: str = "FLIR_Blackfly_S") -> None:
        """
        Exporta a calibração de cor para arquivo YAML legível no padrão do projeto.
        """
        if self.CCM is None:
            raise ValueError("CCM não calculada.")

        metrics = self.evaluate_metrics()
        gains = self.get_flir_gains()

        data = {
            "metadata": {
                "camera_name": camera_name,
                "calibration_date": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                "target_type": self.target_type,
                "target_reference": "macbeth_generator.py (24 patches)",
                "application_note": "https://www.teledynevisionsolutions.com/support/support-center/application-note/iis/using-color-correction/"
            },
            "flir_camera_settings": {
                "isp_enable": True,
                "color_transformation_enable": True,
                "rgb_transform_light_source": "Custom",
                "color_transformation_selector": "RGBtoRGB",
                "gains": gains
            },
            "color_correction_matrix": [
                [float(self.CCM[0, 0]), float(self.CCM[0, 1]), float(self.CCM[0, 2])],
                [float(self.CCM[1, 0]), float(self.CCM[1, 1]), float(self.CCM[1, 2])],
                [float(self.CCM[2, 0]), float(self.CCM[2, 1]), float(self.CCM[2, 2])]
            ],
            "validation_metrics": {
                "rmse_before": metrics["rmse_before"],
                "rmse_after": metrics["rmse_after"],
                "delta_e_mean_before": metrics["delta_e_mean_before"],
                "delta_e_mean_after": metrics["delta_e_mean_after"],
                "improvement_pct": metrics["improvement_pct"]
            }
        }

        os.makedirs(os.path.dirname(os.path.abspath(filepath)), exist_ok=True)
        with open(filepath, "w", encoding="utf-8") as f:
            yaml.dump(data, f, default_flow_style=False, sort_keys=False)
        print(f"Parâmetros FLIR salvos com sucesso em: {filepath}")

